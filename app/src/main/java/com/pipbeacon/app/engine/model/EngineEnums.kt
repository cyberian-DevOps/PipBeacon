package com.pipbeacon.app.engine.model

enum class SignalDirection(val label: String) {
    BUY("BUY"),
    SELL("SELL")
}

enum class SignalApprovalStatus(val label: String, val description: String) {
    EXPERIMENTAL_UNVERIFIED("Experimental (Unverified)", "Generated by local deterministic rules. Not independently verified or backtested."),
    PENDING_PEER_REVIEW("Pending Peer Review", "Undergoing independent rule validation."),
    AUDITED_BENCHMARK("Audited Benchmark", "Passed benchmark criteria under historical forward testing.")
}

enum class SignalOutcomeStatus(val label: String) {
    PENDING("PENDING"),
    HIT_TP1("HIT TP1"),
    HIT_TP2("HIT TP2"),
    HIT_TP3("HIT TP3"),
    STOPPED_OUT("STOPPED OUT"),
    EXPIRED("EXPIRED (TIMED OUT)")
}

enum class TrendClassification(val label: String) {
    STRONG_UPTREND("Strong Uptrend"),
    MODERATE_UPTREND("Moderate Uptrend"),
    CONSOLIDATION_RANGING("Consolidation / Ranging"),
    MODERATE_DOWNTREND("Moderate Downtrend"),
    STRONG_DOWNTREND("Strong Downtrend")
}

data class TechnicalSnapshot(
    val ema20: Double,
    val ema50: Double,
    val ema200: Double,
    val rsi14: Double,
    val macdHistogram: Double,
    val macdLine: Double,
    val macdSignal: Double,
    val atr14: Double,
    val supportLevel: Double,
    val resistanceLevel: Double,
    val trend: TrendClassification
)
